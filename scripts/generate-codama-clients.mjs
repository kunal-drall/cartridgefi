#!/usr/bin/env node
/**
 * Sync Barrier Generator (Wave 1 -> Wave 2):
 * Reads Agent-01's compiled Anchor v1 IDLs from `target/idl/*.json`, copies frozen IDLs
 * into `packages/codama-clients/idl/`, renders zero-hand-rolled `@solana/kit` v8
 * TypeScript clients into `packages/codama-clients/src/generated/<program>/`, and normalizes
 * NodeNext ESM specifiers + `satisfies` contextual plugin typing for `tsc --strict`.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const codamaPkgDir = join(repoRoot, "packages", "codama-clients");
const requireFromCodamaPkg = createRequire(join(codamaPkgDir, "package.json"));

const { createFromRoot } = await import(requireFromCodamaPkg.resolve("codama"));
const { rootNodeFromAnchor } = await import(
  requireFromCodamaPkg.resolve("@codama/nodes-from-anchor")
);
const { renderVisitor } = await import(
  requireFromCodamaPkg.resolve("@codama/renderers-js")
);

const PROGRAMS = [
  { idlName: "cartridge_registry", moduleName: "cartridgeRegistry" },
  { idlName: "cartridge_er_room", moduleName: "cartridgeErRoom" },
  { idlName: "cartridge_vault_router", moduleName: "cartridgeVaultRouter" },
  { idlName: "cartridge_passport", moduleName: "cartridgePassport" },
];

function walkTsFiles(dir) {
  const results = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      results.push(...walkTsFiles(full));
    } else if (full.endsWith(".ts")) {
      results.push(full);
    }
  }
  return results;
}

function normalizeNodeNextImports(filePath) {
  const fileDir = dirname(filePath);
  let src = readFileSync(filePath, "utf8");

  src = src.replace(
    /(from\s+['"])(\.[^'"]*)(['"])/g,
    (match, prefix, spec, suffix) => {
      if (spec.endsWith(".js") || spec.endsWith(".json")) {
        return match;
      }
      if (spec === ".") {
        return `${prefix}./index.js${suffix}`;
      }
      if (spec === "..") {
        return `${prefix}../index.js${suffix}`;
      }
      const candidatePath = resolve(fileDir, spec);
      if (existsSync(candidatePath) && statSync(candidatePath).isDirectory()) {
        return `${prefix}${spec}/index.js${suffix}`;
      }
      return `${prefix}${spec}.js${suffix}`;
    },
  );

  // Convert Codama's `<XxxPlugin>{ ... } });` to contextual typing `{ ... } satisfies XxxPlugin });`
  src = src.replace(
    /<([A-Za-z0-9_]+Plugin)>(\{[\s\S]*?\})\s*\}\);/g,
    "$2 satisfies $1 });",
  );

  writeFileSync(filePath, src, "utf8");
}

const idlSourceDir = join(repoRoot, "target", "idl");
const idlFrozenDir = join(codamaPkgDir, "idl");
const generatedRoot = join(codamaPkgDir, "src", "generated");

mkdirSync(idlFrozenDir, { recursive: true });
mkdirSync(generatedRoot, { recursive: true });

for (const prog of PROGRAMS) {
  const srcPath = join(idlSourceDir, `${prog.idlName}.json`);
  if (!existsSync(srcPath)) {
    throw new Error(`Missing compiled Anchor IDL: ${srcPath}. Run anchor build first.`);
  }
  const destIdlPath = join(idlFrozenDir, `${prog.idlName}.json`);
  copyFileSync(srcPath, destIdlPath);

  const idlJson = JSON.parse(readFileSync(destIdlPath, "utf8"));
  const codama = createFromRoot(rootNodeFromAnchor(idlJson));
  const outDir = join(generatedRoot, prog.moduleName);
  mkdirSync(outDir, { recursive: true });
  await codama.accept(
    renderVisitor(outDir, {
      deleteFolderBeforeRendering: true,
      formatCode: false,
    }),
  );
  const nestedPkgJson = join(outDir, "package.json");
  if (existsSync(nestedPkgJson)) {
    rmSync(nestedPkgJson);
  }
  for (const tsFile of walkTsFiles(outDir)) {
    normalizeNodeNextImports(tsFile);
  }
  console.log(`Generated & normalized @solana/kit Codama client -> ${outDir}`);
}

const barrelLines = [
  "// Auto-generated by scripts/generate-codama-clients.mjs from frozen Anchor IDLs.",
  'export { CARTRIDGE_PROGRAM_IDS } from "@cartridgefi/shared-types";',
  ...PROGRAMS.map(
    (p) =>
      `export * as ${p.moduleName} from "./generated/${p.moduleName}/src/generated/index.js";`,
  ),
  "",
];

writeFileSync(join(codamaPkgDir, "src", "index.ts"), barrelLines.join("\n"), "utf8");
console.log("Updated packages/codama-clients/src/index.ts");
